async function main() {
  const supabaseUrl = envRequired('SUPABASE_URL');
  const serviceKey = envRequired('SUPABASE_SERVICE_ROLE_KEY');

  const rows = [];

  for (const f of FOOD) {
    rows.push({
      id: f.id,
      name: f.name,
      category: f.category,
      subcategory: null,
      preparation: null,
      state: null,
      type: f.type,
      kcal: f.kcal,
      protein: f.protein,
      carbs: f.carbs,
      fat: f.fat,
      fiber: f.fiber,
      serving_basis: '100g',
      standard_serving_grams: f.standardServingGrams ?? null,
      standard_serving_label: STANDARD_SERVING_LABEL_OVERRIDE[f.id] ?? null,
      aliases: f.aliases ?? [],
    });
  }

  for (const b of BEVERAGES) {
    // alcoholic: false → 'Non-alcoholic' subcategory + state, gets
    //              the non-alcoholic aliases.
    // alcoholic: true → 'Alcoholic beverages' subcategory, no NA aliases.
    // alcoholic: undefined → treated as non-alcoholic (back-compat for
    //                    entries added before this flag existed).
    const isAlc = b.alcoholic === true;
    const id = `${isAlc ? 'cur-beer' : 'cur-na'}-${slugify(`${b.brand}-${b.name}-${b.size}`)}`;
    const aliases = isAlc
      ? [b.brand]
      : [b.brand, 'non-alcoholic', 'alcohol-free', 'zero proof'];
    rows.push({
      id,
      name: b.name,
      category: 'Beverages',
      subcategory: isAlc ? 'Alcoholic beverages' : 'Non-alcoholic',
      preparation: null,
      state: isAlc ? null : 'Non-alcoholic',
      type: 'beverage',
      kcal: b.kcal,
      protein: b.protein,
      carbs: b.carbs,
      fat: b.fat,
      fiber: b.fiber,
      serving_basis: '100ml',
      standard_serving_grams: null,
      standard_serving_label: `${b.size} · ${b.brand}`,
      aliases,
    });
  }

  console.log(`Inserting ${rows.length} curated foods (basic + air-fried + pasta + 0% / alcoholic beverages)…`);

  // Batch in groups of 200 to keep payload reasonable.
  const BATCH = 200;
  for (let i = 0; i < rows.length; i += BATCH) {
    const slice = rows.slice(i, i + BATCH);
    await restInsert(supabaseUrl, serviceKey, 'foods', slice);
    console.log(`  …${Math.min(i + BATCH, rows.length)} / ${rows.length}`);
  }

  console.log('Done.');
}

main().catch((err) => {
  console.error('Fatal:', err);
  process.exit(1);
});